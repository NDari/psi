test.case("asks, picks, takes a note and a custom choice", function()
  test.ui.answer("confirm", true)
  test.ui.answer("select", "staging")
  test.ui.answer("input", "first try")
  test.ui.answer("custom", "canary")
  test.command("/deploy")
  test.eq(test.requests("confirm")[1].title, "Deploy?")
  test.eq(test.requests("select")[1].options, { "staging", "production" })
  test.eq(test.requests("append_entry")[1].data, { target = "staging", note = "first try", speed = "canary" })
  test.eq(test.requests("notify")[1].message, "deploying to staging (canary)")
end)

test.case("stops when the user says no", function()
  test.ui.answer("confirm", false)
  test.command("/deploy")
  test.eq(#test.requests("select"), 0)
  test.eq(test.requests("notify")[1].message, "not deployed")
end)

test.case("the tool runs bash through psi", function()
  test.mock_tool("bash", "deployed")
  test.eq(test.tool("deploy", {}).text, "deployed")
  test.eq(test.requests("execute_tool")[1].args, { command = "echo deployed" })
end)
