test.case("the tool adds and completes tasks, kept as entries", function()
  test.eq(test.tool("todo", { action = "add", text = "write tests" }).text, "[ ] 1. write tests")
  local r = test.tool("todo", { action = "done", index = 1 })
  test.contains(r.text, "1. write tests")
  local entries = test.requests("append_entry")
  test.eq(#entries, 2)
  test.eq(entries[2].data, { op = "done", index = 1 })
  -- The status line has nothing open now.
  local status = test.requests("status")
  test.eq(status[#status].text, nil)
end)

test.case("state comes from the branch's entries", function()
  test.set_entries({ { "todo", { op = "add", text = "a" } }, { "todo", { op = "add", text = "b" } } })
  test.eq(test.tool("todo", { action = "list" }).text, "[ ] 1. a\n[ ] 2. b")
  test.eq(test.requests("status")[1].text, "2 open")
end)

test.case("mistakes get a clear message", function()
  local r = test.tool("todo", { action = "done", index = 9 })
  test.eq(r.is_error, true)
  test.eq(r.text, "no task 9; there are 0")
  test.eq(test.tool("todo", { action = "remove" }).text, "action is add, done or list, not remove")
end)

test.case("/todo adds and shows; /todo-next asks the agent", function()
  test.command("/todo", "ship it")
  test.contains(test.requests("notify")[1].message, "1. ship it")
  test.set_entries({ { "todo", { op = "add", text = "ship it" } } })
  test.command("/todo-next")
  test.contains(test.requests("send_user_message")[1].text, "Work on task 1: ship it")
end)

test.case("/todo-share gives the model the list", function()
  test.set_entries({ { "todo", { op = "add", text = "a" } } })
  test.command("/todo-share")
  test.eq(test.requests("send_message")[1], { kind = "send_message", custom_type = "todo", text = "The user's task list:\n[ ] 1. a" })
end)
