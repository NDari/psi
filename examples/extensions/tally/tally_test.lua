local function call(name)
  test.emit("tool_result", { id = "1", name = name, args = {}, text = "", is_error = false })
end

test.case("each tool result is kept as an entry and shown", function()
  call("bash")
  call("read")
  call("bash")
  local entries = test.requests("append_entry")
  test.eq(#entries, 3)
  test.eq(entries[3].data, { tool = "bash" })
  local status = test.requests("status")
  test.eq(status[#status].text, "3 calls")
  local widget = test.requests("widget")
  test.contains(widget[#widget].lines[1], "bash 2  read 1")
end)

test.case("the count comes from the branch's entries", function()
  test.set_entries({ { "tally", { tool = "edit" } }, { "other", { tool = "x" } }, { "tally", { tool = "read" } }, { "tally", { tool = "read" } } })
  test.command("/tally")
  test.eq(test.requests("notify")[1].message, "3 tool calls: read 2, edit 1")
end)

test.case("an empty branch", function()
  test.command("/tally")
  test.eq(test.requests("notify")[1].message, "no tool calls yet")
  test.emit("session_start", {})
  test.eq(test.requests("status")[1].text, nil)
end)

test.case("/tally-share and /tally-ask", function()
  test.set_entries({ { "tally", { tool = "bash" } } })
  test.command("/tally-share")
  test.eq(test.requests("send_message")[1], { kind = "send_message", custom_type = "tally", text = "So far: 1 tool calls: bash 1" })
  test.command("/tally-ask")
  test.contains(test.requests("send_user_message")[1].text, "You have made 1 tool calls: bash 1.")
end)
