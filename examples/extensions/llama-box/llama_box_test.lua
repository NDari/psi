test.case("registers one provider with its model", function()
  local p = test.providers()
  test.eq(#p, 1)
  test.eq(p[1].name, "box")
  test.eq(p[1].base_url, "http://127.0.0.1:9932/v1")
  test.eq(p[1].api_key, "$BOX_KEY")
  test.eq(p[1].models[1].id, "qwen3.6-35b")
  test.eq(p[1].models[1].context_window, 65536)
end)
